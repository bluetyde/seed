#!/usr/bin/env node
// Writes THIRD_PARTY_NOTICES.md from package-lock.json and the licence files of the installed packages.
//   node scripts/gen-notices.cjs            write the file (needs `npm ci --include=dev` first)
//   node scripts/gen-notices.cjs --check    exit 1 when the committed file was made from another package-lock.json (needs no installed packages); `--notices <file>` names another file to write or check
"use strict";
const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const lockPath = path.join(root, "package-lock.json");
const at = process.argv.indexOf("--notices");
const outPath = at >= 0 && process.argv[at + 1] ? path.resolve(process.argv[at + 1]) : path.join(root, "THIRD_PARTY_NOTICES.md");
const lockBytes = fs.readFileSync(lockPath);
const lockSha = crypto.createHash("sha256").update(lockBytes).digest("hex");
const MARK = "Lockfile SHA-256: ";

if (process.argv.includes("--check")) {
  const have = fs.existsSync(outPath) ? fs.readFileSync(outPath, "utf8") : "";
  const m = new RegExp(MARK + "([0-9a-f]{64})").exec(have);
  if (!m || m[1] !== lockSha) {
    console.error("THIRD_PARTY_NOTICES.md is not made from the current package-lock.json: run `node scripts/gen-notices.cjs` and commit the result");
    process.exit(1);
  }
  console.log("THIRD_PARTY_NOTICES.md matches package-lock.json");
  process.exit(0);
}

const lock = JSON.parse(lockBytes.toString("utf8"));
const rows = [];
for (const [key, info] of Object.entries(lock.packages || {})) {
  if (key === "" || !key.includes("node_modules/")) continue;
  const name = key.slice(key.lastIndexOf("node_modules/") + "node_modules/".length);
  const dir = path.join(root, key);
  let license = info.license;
  if (!license && fs.existsSync(path.join(dir, "package.json"))) {
    try {
      const pj = JSON.parse(fs.readFileSync(path.join(dir, "package.json"), "utf8"));
      license = typeof pj.license === "string" ? pj.license : pj.license && pj.license.type;
    } catch {
      // unreadable package.json: left as unknown below
    }
  }
  let text = "";
  if (fs.existsSync(dir)) {
    const file = fs.readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.|$)/i.test(f) && fs.statSync(path.join(dir, f)).isFile());
    if (file) text = fs.readFileSync(path.join(dir, file), "utf8").replace(/\r\n/g, "\n").trim();
  }
  rows.push({ key, name, version: info.version, license: license || "UNKNOWN", dev: info.dev === true || info.devOptional === true, optional: info.optional === true, text });
}
rows.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version) || a.key.localeCompare(b.key));
// one line per package and version, however many places it is installed in; a package SEED runs with outranks the same one used only to build
const seen = new Map();
for (const r of rows) {
  const id = `${r.name}@${r.version}`;
  const prior = seen.get(id);
  if (!prior) seen.set(id, r);
  else if (prior.dev && !r.dev) seen.set(id, r);
}
const unique = [...seen.values()];
const prod = unique.filter((r) => !r.dev);
const dev = unique.filter((r) => r.dev);

const out = [];
out.push("# Third-party notices");
out.push("");
out.push("SEED is released under the MIT licence (see `LICENSE`). It depends on the open source packages below, each under its own licence. This file is generated by `scripts/gen-notices.cjs` from `package-lock.json`; do not edit it by hand.");
out.push("");
out.push(MARK + lockSha);
out.push("");
out.push("Not listed here: the suite apps and the calculation engines (OpenMC, nuclear data, OFFBEAT and others). SEED does not bundle them; each is installed separately and carries its own licence. Electron, listed below, ships with its own notice file for the Chromium and Node.js components it contains (`LICENSES.chromium.html` in the Electron distribution).");
out.push("");
out.push("## Packages SEED runs with");
out.push("");
out.push("| Package | Version | Licence |");
out.push("|---|---|---|");
for (const r of prod) out.push(`| ${r.name} | ${r.version} | ${r.license} |`);
out.push("");
out.push("## Packages used only to build and test SEED");
out.push("");
out.push("Not part of what SEED runs with; listed for completeness.");
out.push("");
out.push("| Package | Version | Licence |");
out.push("|---|---|---|");
for (const r of dev) out.push(`| ${r.name} | ${r.version} | ${r.license} |`);
out.push("");
out.push("## Licence texts of the packages SEED runs with");
out.push("");
out.push("Packages that share the same text are listed together under one copy of it.");
out.push("");
const groups = new Map();
for (const r of prod) {
  const k = r.text || "(this package ships no licence file; its licence is the one named in the table above)";
  if (!groups.has(k)) groups.set(k, []);
  groups.get(k).push(`${r.name} ${r.version}`);
}
let n = 0;
for (const [text, names] of [...groups.entries()].sort((a, b) => b[1].length - a[1].length)) {
  n++;
  out.push(`### ${names.length === 1 ? names[0] : `Text ${n}: ${names.length} packages`}`);
  out.push("");
  if (names.length > 1) {
    out.push(names.join(", "));
    out.push("");
  }
  out.push("```text");
  out.push(text);
  out.push("```");
  out.push("");
}
fs.writeFileSync(outPath, out.join("\n").replace(/[ \t]+$/gm, "") + "\n", "utf8");
console.log(`wrote THIRD_PARTY_NOTICES.md: ${prod.length} packages SEED runs with, ${dev.length} build and test only, ${groups.size} distinct licence texts`);
